#!/usr/bin/env python3
"""Merge data/*.json into questions.js (so the page also works when opened as a local file)."""
import json, os, sys

ROOT = os.path.dirname(os.path.abspath(__file__))

# slug -> (week, title, exam)
LECTURES = [
    ("ehr", 2, "Electronic Health Record Systems", "midterm"),
    ("cognitive", 3, "Cognitive Science & Biomedical Informatics", "midterm"),
    ("imaging", 4, "Biomedical Imaging Informatics", "midterm"),
    ("monitoring", 5, "Patient Monitoring System (iGuardian)", "midterm"),
    ("public_health", 6, "Public Health Informatics", "midterm"),
    ("cdss", 7, "Clinical Decision-Support Systems", "midterm"),
    ("telehealth", 8, "Telehealth & Wearables", "midterm"),
    # Final (week 10-15): add data/<slug>.json, then declare it here
    # ("infrastructure", 10, "Health Information Infrastructure", "final"),
]

def check(q, where):
    t = q.get("type")
    assert t in ("mcq", "fill", "short"), f"{where}: bad type {t}"
    assert isinstance(q.get("q"), str) and q["q"].strip(), f"{where}: empty q"
    if t == "mcq":
        assert isinstance(q.get("options"), list) and len(q["options"]) >= 2, f"{where}: options"
        assert isinstance(q.get("answer"), int) and 0 <= q["answer"] < len(q["options"]), f"{where}: answer idx"
    elif t == "fill":
        assert isinstance(q.get("answer"), list) and q["answer"], f"{where}: fill answers"
    else:
        assert isinstance(q.get("answer"), str), f"{where}: short answer"

def main():
    lectures, questions = [], []
    for slug, week, title, exam in LECTURES:
        path = os.path.join(ROOT, "data", f"{slug}.json")
        if not os.path.exists(path):
            print(f"!! missing {path}", file=sys.stderr)
            continue
        data = json.load(open(path, encoding="utf-8"))
        for i, q in enumerate(data):
            check(q, f"{slug}#{i}")
            q = dict(q)
            q["id"] = f"{slug}-{i+1:03d}"
            q["lecture"] = slug
            q.setdefault("explanation", "")
            questions.append(q)
        lectures.append({"slug": slug, "week": week, "title": title, "exam": exam, "count": len(data)})
        print(f"{slug:15s} {len(data):4d}")
    print(f"{'TOTAL':15s} {len(questions):4d}")
    out = os.path.join(ROOT, "questions.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by build.py — do not edit by hand, edit data/*.json\n")
        f.write("window.QUESTION_BANK = ")
        json.dump({"lectures": lectures, "questions": questions}, f, ensure_ascii=False, indent=1)
        f.write(";\n")

if __name__ == "__main__":
    main()
